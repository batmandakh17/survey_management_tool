"""Build the single-file tool from src/: rtm_interview_tool.html (offline, no network).

Run from this folder:  python3 build.py
The page inlines its stylesheet, the holiday table and the scripts, so it needs no other file and makes no request.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")


def read(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return f.read()


def guard(js):
    # a script element ends at the first "</script"; none of our sources may contain it
    assert "</script" not in js.lower(), "a source file contains </script"
    return js


def risk_js():
    """The trained models and their card (models/), bundled so the page needs no file and no network."""
    m = os.path.join(HERE, "models", "risk_models.json")
    if not os.path.exists(m):
        return "window.RTM_RISK = null; window.RTM_RISK_CARD = '';"
    import json
    card = open(os.path.join(HERE, "models", "MODEL_CARD.md"), encoding="utf-8").read()
    return ("// Generated by build.py from models/risk_models.json and models/MODEL_CARD.md; do not edit by hand.\n"
            f"window.RTM_RISK = {json.dumps(json.load(open(m, encoding='utf-8')), separators=(',', ':'))};\n"
            f"window.RTM_RISK_CARD = {json.dumps(card)};\n")


def build(test_js=None, out=None):
    html = read("shell.html")
    html = html.replace("/*CSS*/", read("app.css"))
    html = html.replace("/*HOLIDAYS*/", guard(read("holidays_data.js")))
    html = html.replace("/*CORE*/", guard(read("core.js")))
    html = html.replace("/*LCORE*/", guard(read("leader_core.js")))
    html = html.replace("/*LSTATS*/", guard(read("leader_stats.js")))
    html = html.replace("/*RISKDATA*/", guard(risk_js()))
    html = html.replace("/*LRISK*/", guard(read("leader_risk.js")) if os.path.exists(os.path.join(SRC, "leader_risk.js")) else "")
    html = html.replace("/*ENUM*/", guard(read("enum_view.js")))
    html = html.replace("/*LEAD*/", guard(read("leader_view.js")) if os.path.exists(os.path.join(SRC, "leader_view.js")) else "")
    html = html.replace("<!--TEST-->", f"<script>{guard(test_js)}</script>" if test_js else "")
    out = out or os.path.join(HERE, "rtm_interview_tool.html")
    with open(out, "w", encoding="utf-8") as f:
        f.write(html)
    # the policy must be the first thing the browser sees about scripts and requests
    assert re.search(r"default-src 'none'", html)
    return out, len(html.encode("utf-8"))


if __name__ == "__main__":
    path, size = build()
    print(f"written {path} ({size / 1024:.0f} KB)")
