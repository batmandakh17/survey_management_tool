"""Holiday tables for the interview tool, generated offline (decision D2).

Source: the Python package `holidays`, the source of handbook Section 3.5.4 (official days off, including
decreed extra days known to the package). Dates the package marks "(estimated)", mostly Islamic holidays in
future years, keep that label so the tool can show them as estimated until a decree confirms them. The tool
itself makes no network call: it reads the table this script writes.

Writes:
  ../src/holidays_data.js        window.RTM_HOLIDAYS = {country: [[date, name, estimated], ...]}
  holidays_<first>_<last>.csv    the same table for people: country, date, name, estimated
Run:  python3 make_holidays.py  [first_year last_year]   (default 2025 2030)
"""
import csv
import json
import os
import sys

import holidays

HERE = os.path.dirname(os.path.abspath(__file__))
# the eleven L2 countries and Mongolia (the guidebook's worked example)
COUNTRIES = {
    "UZ": "Uzbekistan (L2CU)", "TJ": "Tajikistan (L2T)", "KG": "Kyrgyz Republic (L2KGZ)", "KZ": "Kazakhstan (L2Kaz)",
    "PH": "Philippines (L2PHL)", "ID": "Indonesia (L2Indo)", "UA": "Ukraine (L2UKR)", "AM": "Armenia (L2Arm)",
    "GE": "Georgia (L2Geo)", "SO": "Somalia (L2Som)", "MN": "Mongolia (worked example)",
}


def main():
    first, last = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) == 3 else (2025, 2030)
    table, rows = {}, []
    for code in COUNTRIES:
        h = holidays.country_holidays(code, years=range(first, last + 1))
        entries = []
        for d, name in sorted(h.items()):
            # one date can carry several names joined by "; "
            est = "estimated" in name.lower()
            clean = name.replace(" (estimated)", "").replace("(estimated)", "").strip()
            entries.append([d.isoformat(), clean, 1 if est else 0])
            rows.append({"country": code, "date": d.isoformat(), "name": clean, "estimated": 1 if est else 0})
        table[code] = entries
    meta = {"source": f"Python package holidays {holidays.__version__}", "years": [first, last],
            "countries": COUNTRIES,
            "note": "Official days off as the package records them; estimated dates are marked. "
                    "An empty list means the package records no public holidays for those years "
                    "(Ukraine 2026-27: holidays suspended under martial law)."}
    js = ("// Generated by holidays/make_holidays.py; do not edit by hand.\n"
          "window.RTM_HOLIDAYS = " + json.dumps({"meta": meta, "table": table}, ensure_ascii=False, separators=(",", ":")) + ";\n")
    with open(os.path.join(HERE, "..", "src", "holidays_data.js"), "w", encoding="utf-8") as f:
        f.write(js)
    out = os.path.join(HERE, f"holidays_{first}_{last}.csv")
    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["country", "date", "name", "estimated"])
        w.writeheader()
        w.writerows(rows)
    print(f"{len(rows)} holiday dates for {len(COUNTRIES)} countries, {first}-{last}; package {holidays.__version__}")
    for code in COUNTRIES:
        print(f"  {code}: {len(table[code])} dates, {sum(e[2] for e in table[code])} estimated")


if __name__ == "__main__":
    main()
